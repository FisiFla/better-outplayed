//! The token, and the `gamestate_integration_replayed.cfg` the user installs.
//!
//! The app generates the file and the user installs it; the app never writes into game
//! installation directories. Everything here produces text (a token and a file's contents) and
//! the caller decides where to leave it. No code path here touches a game directory.
//!
//! Valve's `"auth" { "token" "<value>" }` block is echoed back by the game inside the JSON body
//! under `"auth"` as a string field; GSI sends no `Authorization` header. So the gate in
//! [`crate::gsi`] compares `body.auth["token"]` in constant time and the generated file puts
//! the token in `"auth"`. The block can carry extra key/value pairs, hence the parser's string
//! map.
//!
//! The token must be stable across runs or the user would re-install the `.cfg` at every start.
//! The first run generates one into the application data directory ([`load_or_create_token`]);
//! later runs read it. It is created `0600` where the platform has modes. On Windows it lives in
//! `%LOCALAPPDATA%\\replayed` (per-user) with no ACL hardening, since the token only gates a
//! listener unreachable from anything but this machine.
//!
//! # The port in the file, and the port the listener bound
//!
//! The file names the endpoint the game posts to, and the two halves are generated by different
//! modules: this one writes the text, [`crate::gsi`] binds the socket. They agree only if the
//! port written here is the port the listener actually bound — which is
//! [`crate::gsi::GsiListener::port`], and not a configured one, because a port that was already
//! taken, or an ephemeral one, are both ways for the game and the listener to disagree and the
//! game would then post into the void. A fixed port is also squat-able: a local process that
//! binds it before replayed starts receives the game's POSTs, and with them the token.
//!
//! # What installing the file costs, and what it leaves behind
//!
//! The file carries the token in the clear, in the game's `cfg` directory. On Windows that
//! directory is readable by the `Users` group, so any local account that can read the game
//! installation can read the token and post forged events. The token has to be readable by the
//! game, so it cannot simply be hidden; what the listener can do about it is scope it (a
//! listener pinned to one game, a port that changes every session) — see
//! [`crate::gsi`]'s module documentation. The rest — an ACL on the installed file, or not
//! writing the token into the game folder at all — is the installing side's business, and the
//! installing side is not this crate.
//!
//! # The containment gap, for whoever fixes it
//!
//! The desktop shell installs the file into the game's `cfg` directory, and it checks that the
//! path is inside the installation before writing. Two facts about that check are not this
//! crate's to fix, and both belong to `apps/desktop/src-tauri/src/paths.rs`:
//!
//! * **The check and the write are not atomic.** The path is resolved (the parent
//!   canonicalised, the last component left alone) and then written, and a write follows a
//!   symlink at the last component. Between the two, a local process can replace the file with
//!   a link and have the token written somewhere else — a classic time-of-check-to-time-of-use
//!   window. Writing through a handle opened with the right flags, or refusing an existing
//!   file, closes it.
//! * **The root is user-writable.** The installation is found through the Steam library
//!   folders, and `libraryfolders.vdf` is a file the user owns. So "inside the installation"
//!   means "under a path the user chose", not "under a path only an administrator can write
//!   to", and a local account that can write the Steam directory can point the library at
//!   anywhere it likes.
//!
//! The facts are recorded here so the fix has them: this crate generates the text and the
//! path, and knows neither of the two problems.

use anyhow::{bail, Context, Result};
use std::path::Path;

/// How many random bytes a token holds: 256 bits, hex-encoded to 64 characters. Valve's example
/// is short, but there is no reason to make a local guess cheap, and a human copies the value
/// once from a file the app wrote.
pub const TOKEN_BYTES: usize = 32;

/// The path the GSI listener answers on when a game is not given one of its own. Anything
/// else is a 404.
pub const DEFAULT_PATH: &str = "/gsi";

/// The path Counter-Strike posts to when it has a path of its own.
pub const CS2_PATH: &str = "/gsi/cs2";

/// The path Dota 2 posts to when it has a path of its own.
pub const DOTA2_PATH: &str = "/gsi/dota2";

/// Valve's app id for Counter-Strike 2 / CS:GO.
pub const CS2_APP_ID: u32 = 730;

/// Valve's app id for Dota 2.
pub const DOTA2_APP_ID: u32 = 570;

/// The path a game posts to.
///
/// The name is the game's own: `"cs2"` and `"dota2"` are the two games the GSI integration
/// serves, and each has a path of its own, so a token lifted from one game's installed
/// `.cfg` is refused on the other's path. An unknown name gets a path derived from it, so
/// a caller that names a game this crate does not know still gets a path that is not
/// another game's.
pub fn game_path(game: &str) -> String {
    let name = game.trim().to_ascii_lowercase();
    match name.as_str() {
        "cs2" | "csgo" | "counter-strike" | "counter-strike 2" => CS2_PATH.to_string(),
        "dota2" | "dota" | "dota 2" => DOTA2_PATH.to_string(),
        other => format!(
            "/gsi/{}",
            other
                .chars()
                .map(|c| if c.is_ascii_alphanumeric() { c } else { '-' })
                .collect::<String>()
        ),
    }
}

/// Generate a token from the operating system's randomness.
pub fn generate_token() -> Result<String> {
    let mut bytes = [0u8; TOKEN_BYTES];
    getrandom::fill(&mut bytes).context("reading randomness for the GSI token")?;
    Ok(hex(&bytes))
}

/// Read the token from `path`, generating and storing one if absent.
///
/// An existing file without a plausible token is an error, not silently replaced: overwriting
/// would leave the user's installed `.cfg` holding a token the listener no longer accepts,
/// which looks exactly like a broken integration.
pub fn load_or_create_token(path: &Path) -> Result<String> {
    match std::fs::read_to_string(path) {
        Ok(text) => {
            let token = text.trim().to_string();
            validate_token(&token).with_context(|| {
                format!(
                    "{} does not hold a usable GSI token; delete it to have a new one \
                     generated (the game's cfg file must then be replaced too)",
                    path.display()
                )
            })?;
            Ok(token)
        }
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
            let token = generate_token()?;
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir)
                    .with_context(|| format!("creating {}", dir.display()))?;
            }
            std::fs::write(path, format!("{token}\n"))
                .with_context(|| format!("writing {}", path.display()))?;
            restrict_to_owner(path);
            Ok(token)
        }
        Err(err) => Err(err).with_context(|| format!("reading {}", path.display())),
    }
}

/// A token must be hex and long enough to be worth having; anything else (a truncated file, an
/// editor's newline handling, a typo) is reported rather than accepted.
fn validate_token(token: &str) -> Result<()> {
    if token.len() != TOKEN_BYTES * 2 {
        bail!("a token is {} hex characters", TOKEN_BYTES * 2);
    }
    if !token.bytes().all(|b| b.is_ascii_hexdigit()) {
        bail!("a token is hex");
    }
    Ok(())
}

/// Owner-only where the platform has file modes. Best effort: not worth refusing to start over.
#[cfg(unix)]
fn restrict_to_owner(path: &Path) {
    use std::os::unix::fs::PermissionsExt;
    let _ = std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600));
}

/// Windows keeps the file in the per-user application data directory; see the module docs.
#[cfg(not(unix))]
fn restrict_to_owner(_path: &Path) {}

/// The data blocks Counter-Strike subscribes to.
const CS2_BLOCKS: &[(&str, &str)] = &[
    ("provider", "1"),
    ("map", "1"),
    ("round", "1"),
    ("bomb", "1"),
    ("player_state", "1"),
    ("player_match_stats", "1"),
];

/// The data blocks Dota 2 subscribes to.
const DOTA_BLOCKS: &[(&str, &str)] = &[
    ("provider", "1"),
    ("map", "1"),
    ("player", "1"),
    ("hero", "1"),
];

/// The Counter-Strike 2 / CS:GO integration file, ready to install.
///
/// Pure text. The tests assert its contents literally, because a human copies it into a game
/// directory and it cannot be checked at run time from here.
///
/// `port` must be the port the listener is bound on ([`crate::gsi::GsiListener::port`]), not a
/// configured one: the file is where the game is told to post, and a port that does not match
/// the socket is a game that posts into the void.
pub fn integration_cfg(port: u16, token: &str) -> String {
    integration_cfg_for(port, DEFAULT_PATH, token, false)
}

/// The Dota 2 integration file. Its data blocks are Dota's, not Counter-Strike's.
pub fn integration_cfg_dota(port: u16, token: &str) -> String {
    integration_cfg_for(port, DEFAULT_PATH, token, true)
}

/// The integration file for a game, posting to `path`.
///
/// The `uri` names the path the game posts to, which is the path the listener serves that
/// game on: each game has a path of its own, so the token in this file is only good for
/// this game. `dota` picks the game's data blocks — Dota 2 subscribes `player` and `hero`,
/// Counter-Strike subscribes `player_state` and `player_match_stats`.
pub fn integration_cfg_for(port: u16, path: &str, token: &str, dota: bool) -> String {
    let (game, install_path, data) = if dota {
        (
            "Dota 2",
            "...\\dota 2 beta\\game\\dota\\cfg\\gamestate_integration\\gamestate_integration_replayed.cfg",
            DOTA_BLOCKS,
        )
    } else {
        (
            "Counter-Strike 2 / CS:GO",
            "...\\Counter-Strike Global Offensive\\game\\csgo\\cfg\\gamestate_integration_replayed.cfg",
            CS2_BLOCKS,
        )
    };
    cfg_text(game, install_path, port, path, token, data)
}

/// The file both of the above are built from. The `//` comments are legal KeyValues (Valve's
/// own `gamestate_integration_consolesample.cfg` uses them) and explain the file to the user,
/// who installs it by hand.
fn cfg_text(
    game: &str,
    install_path: &str,
    port: u16,
    path: &str,
    token: &str,
    data: &[(&str, &str)],
) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "// replayed — {game} Game State Integration (generated)\n"
    ));
    out.push_str("// Install this file as:\n");
    out.push_str(&format!("//   {install_path}\n"));
    out.push_str("// replayed listens on loopback only; nothing here leaves this machine.\n");
    out.push('\n');
    out.push_str("\"replayed\"\n{\n");
    out.push_str(&format!(
        "    \"uri\"       \"http://127.0.0.1:{port}{path}\"\n"
    ));
    // timeout/buffer/throttle are Valve's recommended local values. The heartbeat keeps payloads
    // arriving through a quiet stretch, so heartbeat-based derivation (the bomb timer) is not
    // waiting on a state change that never comes.
    out.push_str("    \"timeout\"   \"1.0\"\n");
    out.push_str("    \"buffer\"    \"0.1\"\n");
    out.push_str("    \"throttle\"  \"0.1\"\n");
    out.push_str("    \"heartbeat\" \"10.0\"\n");
    out.push('\n');
    out.push_str("    // Echoed back in the payload's \"auth\" block; replayed rejects any\n");
    out.push_str("    // request whose token does not match the one it generated.\n");
    out.push_str("    \"auth\"\n    {\n");
    out.push_str(&format!("        \"token\"     \"{token}\"\n"));
    out.push_str("    }\n");
    out.push('\n');
    out.push_str("    \"data\"\n    {\n");
    for (name, value) in data {
        // Both halves are quoted (`"map" "1"`). A missing quote makes the file invalid for the game
        // and nothing here can run the game to find out, hence the test checks rendered lines, not
        // merely the presence of keys.
        out.push_str(&format!("        \"{name}\"{}\n", pad(name, value)));
    }
    out.push_str("    }\n}\n");
    out
}

/// One `"key" "value"` line, aligned as in Valve's own example.
///
/// Never fewer than one space between the tokens: `"player_match_stats""1"` is fragile for a
/// KeyValues parser and may be read as part of the key. The longest name is 18 characters, so
/// this only bites that one line, which a test must catch since nothing here can run the game.
fn pad(name: &str, value: &str) -> String {
    const WIDTH: usize = 20;
    let spaces = WIDTH.saturating_sub(name.len() + 2).max(1);
    format!("{}\"{value}\"", " ".repeat(spaces))
}

fn hex(bytes: &[u8]) -> String {
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push(DIGITS[(byte >> 4) as usize] as char);
        out.push(DIGITS[(byte & 0x0f) as usize] as char);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_generated_token_is_256_bits_of_hex() {
        let token = generate_token().expect("the OS provides randomness");
        assert_eq!(token.len(), TOKEN_BYTES * 2);
        assert!(token.bytes().all(|b| b.is_ascii_hexdigit()), "got {token}");
        assert_eq!(
            token,
            token.to_lowercase(),
            "lower-case hex, so two spellings of one value cannot both exist"
        );
    }

    #[test]
    fn two_generated_tokens_differ() {
        let a = generate_token().unwrap();
        let b = generate_token().unwrap();
        assert_ne!(a, b, "a token that repeats is not random");
    }

    #[test]
    fn the_counter_strike_cfg_is_the_file_a_user_can_install() {
        // A fixed token, not a credential: the digits of pi in hex, the same in every test.
        // The real one is generated from the OS entropy source at run time. `gitleaks:allow`
        // because a hex string assigned to a name containing "token" reads as a leak.
        let token = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"; // gitleaks:allow
        let text = integration_cfg(45671, token);

        // The endpoint, which is the one thing that has to be right.
        assert!(
            text.contains("\"uri\"       \"http://127.0.0.1:45671/gsi\""),
            "the uri must name loopback and the configured port:\n{text}"
        );
        // The token exactly once: a file with it twice would leak it.
        assert_eq!(
            text.matches(token).count(),
            1,
            "the token appears once:\n{text}"
        );
        assert!(
            text.contains("\"auth\"\n    {\n"),
            "in the auth block:\n{text}"
        );
        // The key structure Valve parses.
        assert!(
            text.starts_with("//"),
            "it explains itself to the user:\n{text}"
        );
        assert!(
            text.contains("\"replayed\"\n{"),
            "the block is named:\n{text}"
        );
        assert!(text.trim_end().ends_with('}'), "and closed:\n{text}");
        assert_eq!(
            text.matches('{').count(),
            text.matches('}').count(),
            "every block is closed:\n{text}"
        );
        assert_eq!(
            text.matches('"').count() % 2,
            0,
            "quotes are balanced:\n{text}"
        );
        // Only loopback appears, and no other host is named anywhere in the file.
        assert!(text.contains("127.0.0.1"), "loopback only:\n{text}");
        assert!(!text.contains("0.0.0.0"), "never every interface:\n{text}");
        assert!(
            text.contains("\"player_match_stats\""),
            "the blocks the derivation reads are subscribed:\n{text}"
        );

        // Every subscribed block is a quoted pair. A half-quoted value is a file the game silently
        // ignores, and there is no CS2 here to notice.
        for (name, value) in [
            ("provider", "1"),
            ("map", "1"),
            ("round", "1"),
            ("bomb", "1"),
            ("player_state", "1"),
            ("player_match_stats", "1"),
        ] {
            let pad = " ".repeat((20 - (name.len() + 2)).max(1));
            let expected = format!("        \"{name}\"{pad}\"{value}\"");
            assert!(
                text.contains(&expected),
                "expected the line {expected:?} in:\n{text}"
            );
        }
    }

    #[test]
    fn every_line_of_the_cfg_is_a_block_name_or_a_quoted_pair() {
        // KeyValues is `"key" "value"`. An odd number of quotes, or a value outside quotes, is a file
        // the game will not read, and nothing here can run CS2 to confirm.
        let text = integration_cfg(45671, "0123456789abcdef0123456789abcdef");
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with("//") || line == "{" || line == "}" {
                continue;
            }
            assert_eq!(
                line.matches('"').count() % 2,
                0,
                "a line with an unbalanced quote: {line:?}"
            );
            assert!(
                matches!(line.matches('"').count(), 2 | 4),
                "a KeyValues line is a block name or a key/value pair: {line:?}"
            );
            if line.matches('"').count() == 4 {
                assert!(
                    line.ends_with('"'),
                    "a key/value pair ends with its value's closing quote: {line:?}"
                );
                // `"key"` then at least one space then `"value"`.
                let after_key = &line[line.find('"').expect("an opening quote") + 1..];
                let after_key = &after_key[after_key.find('"').expect("a closing quote") + 1..];
                let separator = after_key.len() - after_key.trim_start().len();
                assert!(
                    separator >= 1,
                    "the key and its value must be separated by whitespace: {line:?}"
                );
                assert!(
                    after_key.trim_start().starts_with('"'),
                    "and the value must be quoted: {line:?}"
                );
            }
        }
        // The same for the Dota file, whose block list differs.
        let dota = integration_cfg_dota(45671, "0123456789abcdef0123456789abcdef");
        for line in dota.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with("//") || line == "{" || line == "}" {
                continue;
            }
            assert!(matches!(line.matches('"').count(), 2 | 4), "{line:?}");
        }
    }

    #[test]
    fn the_dota_cfg_subscribes_dotas_blocks() {
        let token = "ffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff";
        let text = integration_cfg_dota(45671, token);
        assert!(
            text.contains("\"uri\"       \"http://127.0.0.1:45671/gsi\""),
            "got:\n{text}"
        );
        assert_eq!(text.matches(token).count(), 1);
        for block in ["\"provider\"", "\"map\"", "\"player\"", "\"hero\""] {
            assert!(text.contains(block), "Dota needs {block}:\n{text}");
        }
        assert!(
            !text.contains("player_match_stats"),
            "a Counter-Strike block would be noise in a Dota file:\n{text}"
        );
    }

    #[test]
    fn the_port_and_the_path_in_the_file_are_the_ones_the_listener_uses() {
        // The two halves are generated by different modules; this asserts they agree on the endpoint.
        for port in [1024u16, 45671, 65535] {
            let text = integration_cfg(port, "00");
            assert!(
                text.contains(&format!("http://127.0.0.1:{port}{DEFAULT_PATH}")),
                "got:\n{text}"
            );
        }
    }

    #[test]
    fn each_game_posts_to_a_path_of_its_own() {
        // The path is what scopes a token: the file a game is given names the path it posts
        // to, and the listener serves that path with that game's token alone.
        assert_eq!(game_path("cs2"), CS2_PATH);
        assert_eq!(game_path("dota2"), DOTA2_PATH);
        assert_eq!(game_path("CS2"), CS2_PATH, "the name is not case-sensitive");
        assert_eq!(game_path("  dota2  "), DOTA2_PATH, "nor padded");
        assert_ne!(game_path("cs2"), game_path("dota2"));
        assert!(
            game_path("cs2").starts_with('/'),
            "a path is absolute: {}",
            game_path("cs2")
        );

        // A game this crate does not know still gets a path of its own, and not another
        // game's.
        let other = game_path("counter-strike 3");
        assert!(other.starts_with("/gsi/"), "got {other}");
        assert_ne!(other, CS2_PATH);
        assert_ne!(other, DOTA2_PATH);
    }

    #[test]
    fn the_cfg_names_the_path_the_game_posts_to() {
        let token = "0123456789abcdef0123456789abcdef"; // gitleaks:allow
        for (path, dota) in [(CS2_PATH, false), (DOTA2_PATH, true)] {
            let text = integration_cfg_for(45671, path, token, dota);
            assert!(
                text.contains(&format!("\"uri\"       \"http://127.0.0.1:45671{path}\"")),
                "the uri must name the path the game posts to:\n{text}"
            );
            assert_eq!(
                text.matches(token).count(),
                1,
                "the token appears once:\n{text}"
            );
        }

        // The Dota file still subscribes Dota's blocks, and the Counter-Strike file its own.
        let cs2 = integration_cfg_for(45671, CS2_PATH, token, false);
        assert!(cs2.contains("\"player_match_stats\""), "got:\n{cs2}");
        let dota = integration_cfg_for(45671, DOTA2_PATH, token, true);
        assert!(dota.contains("\"hero\""), "got:\n{dota}");
        assert!(!dota.contains("player_match_stats"), "got:\n{dota}");

        // The two old files keep their path and their blocks.
        assert!(integration_cfg(45671, token).contains(DEFAULT_PATH));
        assert!(integration_cfg_dota(45671, token).contains(DEFAULT_PATH));
    }

    #[test]
    fn a_token_file_is_created_once_and_reused_afterwards() {
        let dir = tempfile::tempdir().expect("a temp dir");
        let path = dir.path().join("gsi-token.txt");

        let first = load_or_create_token(&path).expect("the first run generates one");
        assert_eq!(first.len(), TOKEN_BYTES * 2);
        let second = load_or_create_token(&path).expect("the second run reads the same one");
        assert_eq!(
            first, second,
            "a token that changed would break the installed cfg"
        );
        assert!(path.is_file(), "and it is kept for the next run");
    }

    #[cfg(unix)]
    #[test]
    fn a_token_file_is_readable_only_by_its_owner() {
        use std::os::unix::fs::PermissionsExt;
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("gsi-token.txt");
        load_or_create_token(&path).unwrap();
        let mode = std::fs::metadata(&path).unwrap().permissions().mode();
        assert_eq!(mode & 0o777, 0o600, "mode was {mode:o}");
    }

    #[test]
    fn a_token_file_that_does_not_hold_a_token_is_refused_rather_than_replaced() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("gsi-token.txt");

        for content in [
            "",
            "hunter2",
            "0123456789abcdef",
            &"a".repeat(65),
            &"z".repeat(64),
        ] {
            std::fs::write(&path, content).unwrap();
            let err = load_or_create_token(&path).expect_err("not a token");
            assert!(
                format!("{err:#}").contains("delete it"),
                "the error must say what to do: {err:#}"
            );
            assert_eq!(
                std::fs::read_to_string(&path).unwrap(),
                content,
                "and change nothing"
            );
        }
    }

    #[test]
    fn a_token_file_with_trailing_whitespace_still_holds_its_token() {
        // Editors add a newline; that must not invalidate a working installation.
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("gsi-token.txt");
        let token = "ab".repeat(TOKEN_BYTES);
        std::fs::write(&path, format!("  {token}  \n\n")).unwrap();
        assert_eq!(load_or_create_token(&path).unwrap(), token);
    }
}
